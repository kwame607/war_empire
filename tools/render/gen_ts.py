import json
from layout import LAYOUT, SHIPS
M=json.load(open('manifest.json'))
names=sorted(M['sprites'])
L=['// GENERATED by tools/render (3D-rendered sprites). Do not edit by hand.',"import type { ImageSourcePropType } from 'react-native';",'']
L.append('export const TOWN_PPU = %s;'%round(M['ppu'],3))
L.append('export const TOWN_SIN = %s;'%round(M['sin'],4))
t=M['terrain']
L.append("export const TOWN_TERRAIN = { src: require('../../assets/town/terrain.jpg') as ImageSourcePropType, w: %d, h: %d, ox: %s, oy: %s };"%(t['w'],t['h'],t['ox'],t['oy']))
L.append('')
L.append('export type TownSprite = { src: ImageSourcePropType; w: number; h: number; ax: number; ay: number };')
L.append('export const TOWN_SPRITES: Record<string, TownSprite> = {')
for n in names:
    s=M['sprites'][n]
    L.append("  %s: { src: require('../../assets/town/%s.png'), w: %d, h: %d, ax: %s, ay: %s },"%(n,n,s['w'],s['h'],s['ax'],s['ay']))
L.append('};')
open('/home/claude/war-empire/src/data/townAssets.ts','w').write('\n'.join(L)+'\n')
L=['// GENERATED by tools/render (layout of the 3D town). Pure data, no images.','']
L.append('/** Where each business, institution and the keep stands on the island: [sprite, sx, sd] (sx across, sd front-to-back). */')
L.append('export const TOWN_SLOTS: Record<string, { sprite: string; sx: number; sd: number }> = {')
for k,(sp,sx,sd) in LAYOUT.items():
    L.append("  %s: { sprite: '%s', sx: %s, sd: %s },"%(k,sp,sx,sd))
L.append('};')
L.append('export const TOWN_SHIPS: [number, number][] = %s;'%json.dumps([list(s) for s in SHIPS]))
L.append('')
L.append('/** Which keep picture to show for a rank (stage index 0-6). */')
L.append('export function keepSpriteForStage(stage: number): string {')
L.append("  if (stage <= 1) return 'keep0';")
L.append("  if (stage <= 3) return 'keep1';")
L.append("  if (stage <= 5) return 'keep2';")
L.append("  return 'keep3';")
L.append('}')
open('/home/claude/war-empire/src/data/townLayout.ts','w').write('\n'.join(L)+'\n')
