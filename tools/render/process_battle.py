import json, math, os
from PIL import Image
import numpy as np
S='/tmp/claude-0/-home-claude/509012e9-4909-5163-a357-93a24e2ebc94/scratchpad/bat4'
OUT='/home/claude/war-empire/assets/battle'; os.makedirs(OUT,exist_ok=True)
K=0.7; PPU=40*K; SIN=19/math.sqrt(16*16+19*19+16*16)
units={}
for u in ['spearmen','archers','cavalry','heavy']:
    for s in ['p','e']:
        n=f'u_{u}_{s}'; im=Image.open(f'{S}/{n}.png').convert('RGBA'); bb=im.getbbox(); tr=im.crop(bb)
        nw,nh=round(tr.width*K),round(tr.height*K); tr.resize((nw,nh),Image.LANCZOS).save(f'{OUT}/{n}.png',optimize=True)
        units[n]={'w':nw,'h':nh,'ax':round((350-bb[0])*K,1),'ay':round((560-bb[1])*K,1)}
im=Image.open(f'{S}/palisade.png').convert('RGBA'); bb=im.getbbox(); tr=im.crop(bb); nw,nh=round(tr.width*K),round(tr.height*K); tr.resize((nw,nh),Image.LANCZOS).save(f'{OUT}/palisade.png',optimize=True)
units['palisade']={'w':nw,'h':nh,'ax':round((350-bb[0])*K,1),'ay':round((560-bb[1])*K,1)}
fields=['plain','forest','hills','river','desert']
for f in fields:
    im=Image.open(f'{S}/field_{f}.png').convert('RGB').resize((round(1600*K),round(1080*K)),Image.LANCZOS)
    a=np.asarray(im).astype('float32')/255; h,w,_=a.shape
    yy,xx=np.mgrid[0:h,0:w]; nx=(xx/w-0.5)*2; ny=(yy/h-0.5)*2
    vig=1-0.38*np.clip((nx**2*0.8+ny**2*0.9)-0.35,0,1)          # darker corners
    haze=np.clip(1-yy/(h*0.55),0,1)**1.6*0.34                      # distant haze at the top
    hz=np.array([0.80,0.85,0.92]); a=a*vig[...,None]; a=a*(1-haze[...,None])+hz*haze[...,None]
    grain=(np.random.default_rng(3).random((h,w,1))-0.5)*0.025; a=np.clip(a+grain,0,1)
    Image.fromarray((a*255).astype('uint8')).save(f'{OUT}/field_{f}.jpg',quality=84,optimize=True)
L=['// GENERATED by tools/render. Do not edit by hand.',"import type { ImageSourcePropType } from 'react-native';",'',
 f'export const BATTLE_PPU = {PPU};',f'export const BATTLE_SIN = {round(SIN,4)};',
 f'export const BATTLE_FIELD = {{ w: {round(1600*K)}, h: {round(1080*K)}, ox: {round(800*K)}, oy: {round(540*K)} }};','',
 'export const BATTLE_FIELDS: Record<string, ImageSourcePropType> = {']
for f in fields: L.append(f"  {f}: require('../../assets/battle/field_{f}.jpg'),")
L+=['};','','export type BattleSprite = { src: ImageSourcePropType; w: number; h: number; ax: number; ay: number };','export const BATTLE_SPRITES: Record<string, BattleSprite> = {']
for n,v in units.items(): L.append(f"  {n}: {{ src: require('../../assets/battle/{n}.png'), w: {v['w']}, h: {v['h']}, ax: {v['ax']}, ay: {v['ay']} }},")
L.append('};')
open('/home/claude/war-empire/src/data/battleAssets.ts','w').write('\n'.join(L)+'\n')
print(sum(os.path.getsize(f'{OUT}/{f}') for f in os.listdir(OUT))//1024,'KB')
