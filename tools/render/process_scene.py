"""Grade the rendered scene, trim icons, write assets and src/data/investigationAssets.ts"""
import json, os, sys
import numpy as np
from PIL import Image, ImageFilter
S = sys.argv[1]; OUT = '/home/claude/war-empire/assets/investigations'; os.makedirs(OUT, exist_ok=True)
NAMES = {'ring': 'Signet ring', 'dagger': 'Dagger', 'compass': 'Brass compass', 'letter': 'Sealed letter', 'goblet': 'Golden goblet', 'key': 'Iron key', 'purse': 'Coin purse', 'quill': 'Quill and inkwell', 'horn': 'War horn', 'medal': 'Gold medal'}
im = Image.open(f'{S}/tent.png').convert('RGB'); a = np.asarray(im).astype('float32') / 255; h, w, _ = a.shape
yy, xx = np.mgrid[0:h, 0:w]; nx = (xx / w - 0.5) * 2; ny = (yy / h - 0.5) * 2
a *= (1 - 0.55 * np.clip(nx ** 2 * 0.9 + ny ** 2 * 0.8 - 0.25, 0, 1))[..., None]
a = np.clip((a - 0.5) * 1.12 + 0.5, 0, 1); a[..., 0] *= 1.04; a[..., 2] *= 0.94
bl = np.asarray(Image.fromarray((a * 255).astype('uint8')).filter(ImageFilter.GaussianBlur(18))).astype('float32') / 255
a = np.clip(a + 0.18 * np.clip(bl - 0.55, 0, 1), 0, 1)
a = np.clip(a + (np.random.default_rng(1).random((h, w, 1)) - 0.5) * 0.02, 0, 1)
Image.fromarray((a * 255).astype('uint8')).resize((1280, 880), Image.LANCZOS).save(f'{OUT}/tent.jpg', quality=84, optimize=True)
hs = json.load(open(f'{S}/hotspots.json'))['tent']
L = ['// GENERATED by tools/render/process_scene.py. Do not edit by hand.', "import type { ImageSourcePropType } from 'react-native';", '',
     'export const SCENE_ASSETS: Record<string, { image: ImageSourcePropType; aspect: number; items: { id: string; name: string; icon: ImageSourcePropType; x: number; y: number }[] }> = {', "  tent: {", "    image: require('../../assets/investigations/tent.jpg'),", f'    aspect: {w / h:.4f},', '    items: [']
for k, (x, y) in hs.items():
    ic = Image.open(f'{S}/icon_{k}.png').convert('RGBA'); bb = ic.getbbox(); ic = ic.crop(bb); m = max(ic.size); sq = Image.new('RGBA', (m, m), (0, 0, 0, 0)); sq.paste(ic, ((m - ic.width) // 2, (m - ic.height) // 2)); sq.resize((112, 112), Image.LANCZOS).save(f'{OUT}/i_{k}.png', optimize=True)
    L.append(f"      {{ id: '{k}', name: '{NAMES[k]}', icon: require('../../assets/investigations/i_{k}.png'), x: {x / w:.4f}, y: {y / h:.4f} }},")
L += ['    ],', '  },', '};', '']
open('/home/claude/war-empire/src/data/investigationAssets.ts', 'w').write('\n'.join(L))
print('ok', len(hs))
